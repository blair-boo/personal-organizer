-- Aba Storage: caixas de armazenamento com etiqueta (rMQR) e o que há dentro.
-- Cada caixa tem um número (vira o código C-014 da etiqueta), os itens ficam em
-- storage_itens (nome, quantidade opcional, classificação opcional), as
-- observações em storage_obs e as fotos/anexos em storage_anexos.
-- Os arquivos vão para o bucket privado `confidencial` (criado na 0010, com a
-- policy de acesso só autenticado), na subpasta `storage/`.
create table storage (
    id uuid primary key default gen_random_uuid(),
    numero integer generated by default as identity unique,
    nome text not null,
    ordem integer not null default 0,
    criado_em timestamptz not null default now()
);

create table storage_categorias (
    id uuid primary key default gen_random_uuid(),
    nome text not null,
    ordem integer not null default 0
);

create unique index uq_storage_categorias_nome on storage_categorias (lower(nome));

create table storage_itens (
    id uuid primary key default gen_random_uuid(),
    storage_id uuid not null references storage(id) on delete cascade,
    nome text not null,
    quantidade integer check (quantidade is null or quantidade > 0),
    categoria_id uuid references storage_categorias(id) on delete set null,
    ordem integer not null default 0,
    criado_em timestamptz not null default now()
);

create index idx_storage_itens_storage on storage_itens(storage_id, ordem);
create index idx_storage_itens_categoria on storage_itens(categoria_id);

create table storage_obs (
    id uuid primary key default gen_random_uuid(),
    item_id uuid not null references storage_itens(id) on delete cascade,
    texto text not null,
    ordem integer not null default 0
);

create index idx_storage_obs_item on storage_obs(item_id, ordem);

create table storage_anexos (
    id uuid primary key default gen_random_uuid(),
    item_id uuid not null references storage_itens(id) on delete cascade,
    nome text not null,
    arquivo_url text not null,
    nome_arquivo text not null,
    criado_em timestamptz not null default now()
);

create index idx_storage_anexos_item on storage_anexos(item_id);

-- RLS: mesmo padrão do resto do app (app de usuário único, só exige login).
alter table storage enable row level security;
alter table storage_categorias enable row level security;
alter table storage_itens enable row level security;
alter table storage_obs enable row level security;
alter table storage_anexos enable row level security;

create policy "authenticated_full_access_storage" on storage
    for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "authenticated_full_access_storage_categorias" on storage_categorias
    for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "authenticated_full_access_storage_itens" on storage_itens
    for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "authenticated_full_access_storage_obs" on storage_obs
    for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "authenticated_full_access_storage_anexos" on storage_anexos
    for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
